import type { SkillName } from '../store/useGameStore';
import type { CurrencyCost } from '../store/useCurrencyStore';

export type ItemType = 'armor' | 'weapon' | 'pet' | 'furniture' | 'consumable' | 'cosmetic' | 'pet_accessory';
export type ItemCategory = 'hygiene' | 'sleep' | 'general' | 'combat' | 'social';

export interface UnlockRequirement {
    skills?: Array<{ skill: SkillName; level: number }>;
    defense?: number;
    attack?: number;
    otherItems?: string[]; // Must own these items first
}

export interface ItemStats {
    attack?: number;
    defense?: number;
    magicAttack?: number;
    magicDefense?: number;
    maxMana?: number;
    bonusXp?: Partial<Record<SkillName, number>>; // Percentage bonus
}

export interface Item {
    id: string;
    name: string;
    description: string;
    icon: string;
    image?: string;
    type: ItemType;
    category?: ItemCategory;

    unlockRequirement: UnlockRequirement;
    cost: CurrencyCost;
    stats?: ItemStats;

    // Display
    rarity?: 'common' | 'uncommon' | 'rare' | 'epic' | 'legendary';
}

