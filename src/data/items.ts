// Helper to get items by type
export function getItemsByType(type: ItemType): Item[] {
    return Object.values(ITEM_DATABASE).filter(item => item.type === type);
}

// Helper to get items by category
export function getItemsByCategory(category: ItemCategory): Item[] {
    return Object.values(ITEM_DATABASE).filter(item => item.category === category);
}
